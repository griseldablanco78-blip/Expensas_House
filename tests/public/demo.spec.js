const {test,expect}=require('@playwright/test');
test('PUBLIC-01: login, ofertas reales, OCR, descuento, gasto y comprobante desde Vercel',async({page})=>{
  const mode=await (await page.request.get('/api/system/info')).json();
  expect(mode.mode,'La prueba pública solo permite entornos de demostración').toBe('demo');
  await page.goto('/');
  await page.locator('#auth-email').fill('test123');
  await page.locator('#auth-password').fill('PruebasTest1234');
  await page.locator('#auth-submit').click();
  await expect(page.locator('#app-shell')).toBeVisible({timeout:30000});
  await expect(page.locator('#environment-notice')).toBeVisible();
  await page.locator('#ai-search-input').fill('leche entera');
  await page.locator('#btn-ai-search').click();
  await expect.poll(()=>page.locator('.store-card').count(),{timeout:30000}).toBeGreaterThan(0);
  console.log('Ofertas reales visibles:',await page.locator('.store-card').count());
  await page.locator('[data-tab="budget"]').click();
  const month=await page.locator('#expense-month').inputValue();
  const before=await (await page.request.get('/api/budget?month='+month)).json();
  await page.locator('#receipt-photo').setInputFiles(require('path').join(__dirname,'../fixtures/ticket-sintetico.png'));
  await page.locator('#receipt-scan').click();
  await expect(page.locator('#receipt-lines tr')).toHaveCount(2,{timeout:45000});
  const first=page.locator('#receipt-lines tr').first();
  await first.locator('[data-field="detail"]').fill('Lectura de prueba desde Vercel');
  await first.locator('[data-field="discount"]').fill('55');
  await page.locator('#receipt-total').fill('2645');
  const store='Super QA pública '+Date.now();
  await page.locator('#receipt-store').fill(store);
  await page.locator('#receipt-confirm').click();
  await expect(page.locator('#receipt-status')).toContainText('Ticket registrado',{timeout:30000});
  await expect(page.locator('#expense-products-body')).toContainText(store,{timeout:30000});
  const after=await (await page.request.get('/api/budget?month='+month)).json();
  expect(after.totalSpent).toBeCloseTo(before.totalSpent+2645,2);
  const expenseRow=page.locator('#expenses-table-body tr').filter({hasText:store});
  const image=await expenseRow.getByText('Ver comprobante').getAttribute('href');
  expect((await page.request.get(image)).status()).toBe(200);
  const text=await expenseRow.getByText('Descargar texto').getAttribute('href');
  expect(await (await page.request.get(text)).text()).toContain('descuento 55');
});
